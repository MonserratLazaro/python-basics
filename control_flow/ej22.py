personas = 20
gatos = 30
perros = 15

if personas < gatos:
  print ("¡Hay demasiados gatos!")

if personas > gatos:
  print("¡No hay tantos gatos!")

if personas < perros:
  print("¡Hay muchos perros!")

if personas > perros:
  print("¡No hay más perros que personas!")

perros += 5

if personas >= perros:
  print("Personas es mayor o igual a perros")

if personas <= perros:
  print("Personas es menor o igual a perros")

if personas == perros:
  print("Personas son perros")